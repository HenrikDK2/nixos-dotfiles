#!/usr/bin/env python3
"""Interleaved A/B(/C...) benchmark of start.sh / exit.sh on a fake system.

usage: ab.py [options] NAME=SRC [NAME=SRC ...]
  SRC: a directory holding start.sh and exit.sh (the gameboost dir of a tree)

One fake root is generated by gen.py for --scenario; each SRC's scripts are
rewritten by prep.sh into ROOT/scripts/NAME. Everything then runs inside one
mount namespace (ns.sh: ROOT/sys at /sys, ROOT/run at /run, ROOT/proc at
/home), so the scripts see the real path lengths. /run is restored from a
copy before every run; sysfs values written by earlier runs stay (the work
done does not depend on them).

Modes (--mode):
  entry  start.sh until its first `sleep` (game-mode entry latency)
  start  start.sh including the follow-up steps (sleeps stubbed to 0 s)
  exit   exit.sh with the state/cups files a full start.sh run of the FIRST
         source left (copied to every root), i.e. the normal game-exit path
  exit-nostate  exit.sh without any state file (fallback paths)

Metrics:
  wall    perf_counter around the run (fork+exec of bash included)
  cpu     user+sys of the whole process tree (RUSAGE_CHILDREN delta)
  --count also: execve and clone/fork counts (strace -f), syscalls made by
          the main bash process (strace -c, no -f), and instructions executed
          in bash processes (callgrind, forked subshells included, exec'd
          programs not traced)
"""
import argparse
import glob
import os
import re
import resource
import shutil
import statistics
import subprocess
import sys
import time

B = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("srcs", nargs="+")
ap.add_argument("--scenario", default="desktop-sysfs")
ap.add_argument("--mode", default="entry")
ap.add_argument("-n", "--runs", type=int, default=30)
ap.add_argument("--warmup", type=int, default=3)
ap.add_argument("--work", default=os.path.join(B, "..", "abwork"))
ap.add_argument("--count", action="store_true")
ap.add_argument("--no-time", action="store_true")
ap.add_argument("--real-procs", type=int, default=0,
                help="exit modes: run in a new PID namespace with N extra sleeping processes, "
                     "exit.sh on the real /proc with the real pgrep (killall etc. stubbed)")
ap.add_argument("--hook", action="store_true",
                help="start mode: run the scenario's sleep hook (bumps thread run times "
                     "during the render sample; render-busy* scenarios bump every game thread)")
ap.add_argument("--gen", default="", help="extra gen.py args, e.g. '--cpus 16 --procs 800'")
a = ap.parse_args()

work = os.path.realpath(a.work)
os.makedirs(work, exist_ok=True)
root = f"{work}/root"
srcs = []
for s in a.srcs:
    name, _, path = s.partition("=")
    srcs.append((name, os.path.realpath(path), root))
INNER = os.environ.get("GB_AB_INNER") == "1"

if a.real_procs and a.mode not in ("exit", "exit-nostate"):
    sys.exit("--real-procs is for the exit modes")
ENV_BASE = {"LC_ALL": "C", "PATH": f"{B}/build/{'bin-realpg' if a.real_procs else 'bin'}:/usr/bin:/bin"}


if not INNER:
    subprocess.run([sys.executable, f"{B}/gen.py", root, a.scenario] + a.gen.split(), check=True,
                   stdout=subprocess.DEVNULL)
    for name, src, _ in srcs:
        subprocess.run([f"{B}/prep.sh", src, f"{root}/scripts/{name}"], check=True,
                       env=dict(os.environ, NO_PROC_REWRITE="1" if a.real_procs else ""))
    shutil.copytree(f"{root}/run", f"{root}/run.orig")
    os.environ["GB_AB_INNER"] = "1"
    pre = ["unshare", "-p", "-f", "--mount-proc"] if a.real_procs else []
    os.execvp(pre[0] if pre else f"{B}/ns.sh", pre + [f"{B}/ns.sh", root, sys.executable] + sys.argv)

SLEEPERS = []
if a.real_procs:
    for i in range(a.real_procs):
        SLEEPERS.append(subprocess.Popen(["sleep", "3600"]))


def reap():
    # we are PID 1 of the namespace with --real-procs: orphans (e.g. a <(pgrep)
    # bash did not wait for) are reparented to us; reap them so their CPU counts
    if not a.real_procs:
        return
    time.sleep(0.02)
    try:
        while os.waitpid(-1, os.WNOHANG)[0] > 0:
            pass
    except ChildProcessError:
        pass


def setup(name, src, root):
    env = dict(ENV_BASE, GB_RESP=f"{root}/resp", GB_FLAG="/run/gameboost/running.flag",
               GB_LOG="/dev/null")
    for line in open(f"{root}/env"):
        k, _, v = line.strip().partition("=")
        if k:
            env[k] = v
    if "GB_REJECT" in env:
        env["LD_PRELOAD"] = f"{B}/build/reject.so"
    if a.mode == "entry":
        env["GB_SLEEP_STOP"] = "1"
    if a.hook:
        env["GB_SLEEP_HOOK"] = f"{root}/sleep_hook"
    args = open(f"{root}/args").read().split()
    return env, args


def restore(root):
    # /run is a bind mount: empty it and copy back, keeping the mount point
    for e in os.listdir("/run"):
        p = os.path.join("/run", e)
        shutil.rmtree(p) if os.path.isdir(p) and not os.path.islink(p) else os.unlink(p)
    for e in os.listdir(f"{root}/run.orig"):
        p = os.path.join(f"{root}/run.orig", e)
        if os.path.isdir(p):
            shutil.copytree(p, os.path.join("/run", e))
        else:
            shutil.copy(p, "/run")


envs = {}
for name, src, root in srcs:
    envs[name] = setup(name, src, root)

if a.mode == "exit":
    # state from a full start.sh run of the first source, used for every run
    name0 = srcs[0][0]
    env0, args0 = envs[name0]
    e = dict(env0)
    e.pop("GB_SLEEP_STOP", None)
    restore(root)
    subprocess.run(["bash", f"{root}/scripts/{name0}/start.sh"] + args0, env=e,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for f in ("state", "cups"):
        if os.path.exists(f"{root}/run/gameboost/{f}"):
            shutil.copy(f"{root}/run/gameboost/{f}", f"{root}/run.orig/gameboost/{f}")
    flag = f"{root}/run.orig/gameboost/running.flag"
    if os.path.exists(flag):
        os.unlink(flag)  # gameboostd removes it before exit.sh


def cmd(name, root):
    env, args = envs[name]
    if a.mode in ("entry", "start"):
        return ["bash", f"{root}/scripts/{name}/start.sh"] + args, env
    return ["bash", f"{root}/scripts/{name}/exit.sh"], env


def once(name, root):
    restore(root)
    c, env = cmd(name, root)
    r0 = resource.getrusage(resource.RUSAGE_CHILDREN)
    t0 = time.perf_counter()
    subprocess.run(c, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    t1 = time.perf_counter()
    reap()
    r1 = resource.getrusage(resource.RUSAGE_CHILDREN)
    cpu = (r1.ru_utime - r0.ru_utime) + (r1.ru_stime - r0.ru_stime)
    return (t1 - t0) * 1000, cpu * 1000


def q(xs, p):
    xs = sorted(xs)
    k = (len(xs) - 1) * p
    f = int(k)
    c = min(f + 1, len(xs) - 1)
    return xs[f] + (xs[c] - xs[f]) * (k - f)


def summary(xs):
    return (f"median {statistics.median(xs):8.2f}  IQR {q(xs, .25):7.2f}-{q(xs, .75):7.2f}  "
            f"min-max {min(xs):7.2f}-{max(xs):7.2f}")


print(f"# scenario={a.scenario} mode={a.mode} gen='{a.gen}' runs={a.runs} real_procs={a.real_procs}")
if a.count:
    for name, src, root in srcs:
        c, env = cmd(name, root)
        restore(root)
        out = f"{work}/strace.{name}"
        subprocess.run(["strace", "-f", "-qq", "-e", "trace=execve,clone,clone3,fork,vfork",
                        "-o", out] + c, env=env, stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL)
        txt = open(out).read()
        execs = len(re.findall(r"execve\(", txt)) - 1  # minus the bash itself
        forks = len(re.findall(r"\b(clone3?|v?fork)\(", txt))
        restore(root)
        out2 = f"{work}/stracec.{name}"
        subprocess.run(["strace", "-c", "-o", out2] + c, env=env, stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL)
        m = re.search(r"^100\.00\s+\S+\s+\S+\s+(\d+)\s+(\d+)?\s*total", open(out2).read(), re.M)
        main_sys = m.group(1) if m else "?"
        restore(root)
        for f in glob.glob(f"{work}/cg.{name}.*"):
            os.unlink(f)
        subprocess.run(["valgrind", "--tool=callgrind", "--trace-children=no",
                        f"--callgrind-out-file={work}/cg.{name}.%p"] + c, env=env,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        ir = 0
        for f in glob.glob(f"{work}/cg.{name}.*"):
            for line in open(f):
                if line.startswith("totals:") or line.startswith("summary:"):
                    ir += int(line.split()[1])
                    break
        print(f"COUNT {name:12s} execs={execs:3d} forks={forks:3d} main_bash_syscalls={main_sys:>6s} "
              f"bash_Ir={ir:,}")
    sys.stdout.flush()

if a.no_time:
    sys.exit(0)
wall = {n: [] for n, _, _ in srcs}
cpu = {n: [] for n, _, _ in srcs}
order = list(srcs)
for i in range(a.warmup + a.runs):
    for name, src, root in order:
        w_, c_ = once(name, root)
        if i >= a.warmup:
            wall[name].append(w_)
            cpu[name].append(c_)
    order = order[1:] + order[:1]  # rotate: alternate who goes first
base = srcs[0][0]
for name, _, _ in srcs:
    dw = (statistics.median(wall[base]) - statistics.median(wall[name])) / statistics.median(wall[base]) * 100
    dc = (statistics.median(cpu[base]) - statistics.median(cpu[name])) / statistics.median(cpu[base]) * 100
    print(f"WALL  {name:12s} ms {summary(wall[name])}  vs {base}: {dw:+.1f}%")
    print(f"CPU   {name:12s} ms {summary(cpu[name])}  vs {base}: {dc:+.1f}%")
